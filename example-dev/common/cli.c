typedef struct {
    bool iv_is_public;
    bool key_is_public;
    bool plaintext_is_public;
} policy_t;

#define ASSERT(cond, msg)                                                                          \
    if (!(cond)) {                                                                                 \
        fprintf(stderr, "Assertion failed: %s\n", msg);                                            \
        exit(EXIT_FAILURE);                                                                        \
    }

// =================================================================================================
// Command line interface
// =================================================================================================
static void print_usage(const char *program)
{
    fprintf(stderr, "Usage: %s -d data_file -p policy_file -o output_file\n", program);
    fprintf(stderr, "  -h         Show this help message\n");
    fprintf(stderr, "  -d file    File containing input data, which includes both private and "
                    "public inputs.\nThis file is normally generated by a fuzzer\n");
    fprintf(stderr, "  -p file    File describing the data classification policy\n");
    fprintf(stderr, "  -o file    Output file\n");
}

static int read_args(int argc, char *argv[], char **data_file, char **policy_file,
                     char **output_fname)
{
    int opt;
    while ((opt = getopt(argc, argv, "d:p:o:h")) != -1) {
        switch (opt) {
        case 'd':
            *data_file = optarg;
            break;
        case 'p':
            *policy_file = optarg;
            break;
        case 'o':
            *output_fname = optarg;
            break;
        case 'h':
            print_usage(argv[0]);
            return 1;
        default:
            print_usage(argv[0]);
            return 1;
        }
    }

    // Check required arguments
    if (!*data_file || !*policy_file || !*output_fname) {
        print_usage(argv[0]);
        return 1;
    }

    return 0; // success
}

