/// @brief Read entire file into buffer
static int read_file(const char *filename, uint8_t **buffer, size_t *size, size_t min_size,
                     size_t max_size)
{
    FILE *file = fopen(filename, "rb");
    if (!file) {
        fprintf(stderr, "Error: Cannot open file %s: %s\n", filename, strerror(errno));
        return -1;
    }

    // Get file size
    struct stat st;
    if (fstat(fileno(file), &st) != 0) {
        fprintf(stderr, "Error: Cannot stat file %s: %s\n", filename, strerror(errno));
        fclose(file);
        return -1;
    }

    if (st.st_size == 0) {
        fprintf(stderr, "Error: File %s is empty\n", filename);
        fclose(file);
        return -1;
    }

    if ((size_t)st.st_size < min_size) {
        fprintf(stderr, "Error: File %s is too small (%ld bytes, min %zu)\n", filename, st.st_size,
                min_size);
        fclose(file);
        return -1;
    }

    if ((size_t)st.st_size > max_size) {
        fprintf(stderr, "Error: File %s is too large (%ld bytes, max %zu)\n", filename, st.st_size,
                max_size);
        fclose(file);
        return -1;
    }

    *buffer = malloc(st.st_size);
    if (!*buffer) {
        fprintf(stderr, "Error: Cannot allocate %ld bytes for file %s\n", st.st_size, filename);
        fclose(file);
        return -1;
    }

    size_t bytes_read = fread(*buffer, 1, st.st_size, file);
    if (bytes_read != (size_t)st.st_size) {
        fprintf(stderr, "Error: Only read %zu of %ld bytes from %s\n", bytes_read, st.st_size,
                filename);
        free(*buffer);
        *buffer = NULL;
        fclose(file);
        return -1;
    }

    *size = st.st_size;
    fclose(file);
    return 0;
}

static int write_output(const char *filename, const uint8_t *data, size_t size)
{
    FILE *file = fopen(filename, "wb");
    if (!file) {
        fprintf(stderr, "Error: Cannot open output file %s: %s\n", filename, strerror(errno));
        return -1;
    }

    size_t bytes_written = fwrite(data, 1, size, file);
    if (bytes_written != size) {
        fprintf(stderr, "Error: Only wrote %zu of %zu bytes to output file %s\n", bytes_written,
                size, filename);
        fclose(file);
        return -1;
    }

    fclose(file);
    return 0;
}

